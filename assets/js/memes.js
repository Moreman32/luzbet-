// Raw pick for structured entries (promo pairs etc.). Cosmetic randomness only.
export function pick(ctx) { const l = CATALOG[ctx] || []; return l[Math.floor(Math.random() * l.length)]; }
export const lines = (ctx) => [...(CATALOG[ctx] || [])];
export function meme(ctx, vars = {}) {
  const list = CATALOG[ctx];
  if (!list || !list.length) return "";
  const fresh = list.filter((x) => !recent.includes(x));
  const pool = fresh.length ? fresh : list;
  const line = pool[Math.floor(Math.random() * pool.length)]; // cosmetic randomness only
  recent.push(line); if (recent.length > 16) recent.shift();
  return line.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? Number(vars[k]).toLocaleString("ru-RU") : ""));
}

// Chooses the outcome context for a finished round. Big-win threshold: ≥ 10× stake or ≥ 5 000 ЛК net.
export function outcomeContext({ bet, payout, extra }) {
  const net = payout - bet;
  if (extra) return extra;
  if (payout === 0) return "loss";
  if (net === 0) return "push";
  if (net < 0) return "loss";
  return net >= 5000 || payout >= bet * 10 ? "win.big" : "win.small";
}
